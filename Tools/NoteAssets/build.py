"""Builds the note highway's gem models and their textures. Plain Python 3, no packages:

    python3 Tools/NoteAssets/build.py

Writes Assets/Models/Notes/{DrumGem,CymbalGem,CymbalRing,KickBar}.obj and
Assets/Textures/Notes/*.png (with a .meta each where one is missing). Delete the cooked twins
(.assbin, .dds) after changing anything here; a tools build recooks them on the next run.

Models: one unit wide (x from -0.5 to 0.5), base at y = 0, real height and depth, symmetric front
to back. NoteHighwayCore scales x to the lane, so sizes along x are fractions of the note's width.

Shading: the highway has no lights of its own, so the look is in two ramp textures per family.
Every vertex's u is its x across the note and its v a place on the ramp, bottom to top:

    trim   a pale base lit by whatever light there is (the diffuse ramp; the material's colour
           stays near white)
    seam   a dark groove between trim and body
    body   the sides, glowing in the lane colour (the emissive ramp times the material's
           emissive colour), brighter toward the top
    hot    a thin crest brighter than the rest, which the bloom picks up
    panel  the top

NoteHighwayCore colours a note through the material's emissive colour only.
"""
import json
import math
import secrets
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = ROOT / 'Assets/Models/Notes'
TEXTURES = ROOT / 'Assets/Textures/Notes'

# Ramp bands (v ranges). Vertices stay inside a band; the gaps between bands absorb filtering.
TRIM = (0.02, 0.18)
SEAM = (0.22, 0.28)
BODY = (0.31, 0.59)
HOT = (0.63, 0.67)
PANEL = (0.72, 0.98)


# ---------------------------------------------------------------- meshes

class Mesh:
    def __init__(self, name):
        self.name = name
        self.vertices = []   # (position, uv, smoothing group)
        self.faces = []      # (a, b, c)

    def vertex(self, position, v, group):
        u = 0.03 + 0.94 * (position[0] + 0.5)
        self.vertices.append((position, (u, v), group))
        return len(self.vertices) - 1

    def triangle(self, a, b, c, facing):
        """Wound so its normal points along `facing`."""
        pa, pb, pc = (self.vertices[i][0] for i in (a, b, c))
        normal = cross(sub(pb, pa), sub(pc, pa))
        if dot(normal, facing) < 0.0:
            b, c = c, b
        if length(normal) > 1e-12:
            self.faces.append((a, b, c))

    def band(self, lower, upper, v, group, facing):
        """A strip between two rings of points (same count). facing: 'out', 'in', 'up'."""
        count = len(lower)
        lo = [self.vertex(p, v[0], group) for p in lower]
        hi = [self.vertex(p, v[1], group) for p in upper]
        for i in range(count):
            j = (i + 1) % count
            mid = scale(add(add(lower[i], lower[j]), add(upper[i], upper[j])), 0.25)
            if facing == 'up':
                direction = (0.0, 1.0, 0.0)
            else:
                sign = 1.0 if facing == 'out' else -1.0
                # Slightly up as well, so a nearly level strip still winds the right way.
                direction = (mid[0] * sign, 0.02, mid[2] * sign)
            self.triangle(lo[i], lo[j], hi[j], direction)
            self.triangle(lo[i], hi[j], hi[i], direction)

    def cap(self, ring, centre, v, group):
        """A fan from a ring up to a centre point."""
        rim = [self.vertex(p, v[0], group) for p in ring]
        middle = self.vertex(centre, v[1], group)
        for i in range(len(ring)):
            self.triangle(rim[i], rim[(i + 1) % len(ring)], middle, (0.0, 1.0, 0.0))

    def normals(self):
        """Area-weighted, smoothed across vertices that share a position and a group."""
        sums = {}
        key = lambda i: (tuple(round(c, 6) for c in self.vertices[i][0]), self.vertices[i][2])
        for a, b, c in self.faces:
            pa, pb, pc = (self.vertices[i][0] for i in (a, b, c))
            normal = cross(sub(pb, pa), sub(pc, pa))
            for i in (a, b, c):
                sums[key(i)] = add(sums.get(key(i), (0.0, 0.0, 0.0)), normal)
        return [normalize(sums.get(key(i), (0.0, 1.0, 0.0))) for i in range(len(self.vertices))]

    def write(self):
        normals = self.normals()
        lines = ['# Generated by Tools/NoteAssets/build.py', 'o ' + self.name]
        lines += ['v %.6f %.6f %.6f' % p for p, _, _ in self.vertices]
        lines += ['vt %.6f %.6f' % uv for _, uv, _ in self.vertices]
        lines += ['vn %.6f %.6f %.6f' % n for n in normals]
        lines += ['f ' + ' '.join('%d/%d/%d' % (i + 1, i + 1, i + 1) for i in face) for face in self.faces]
        MODELS.mkdir(parents=True, exist_ok=True)
        path = MODELS / (self.name + '.obj')
        path.write_text('\n'.join(lines) + '\n')
        write_meta(path, {'ConvertUnits': False, 'FileType': 'obj'})
        print('%s: %d vertices, %d triangles' % (path.relative_to(ROOT), len(self.vertices), len(self.faces)))


def add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def scale(a, s): return (a[0] * s, a[1] * s, a[2] * s)
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def length(a): return math.sqrt(dot(a, a))
def normalize(a):
    size = length(a)
    return scale(a, 1.0 / size) if size > 1e-12 else (0.0, 1.0, 0.0)


def rounded_rect(half_width, half_depth, radius, inset, y, segments=6):
    """A rounded rectangle in the xz plane, pulled in by `inset` on every side."""
    w, d = half_width - inset, half_depth - inset
    r = max(radius - inset, 0.004)
    points = []
    for corner, (sx, sz) in enumerate(((1, 1), (-1, 1), (-1, -1), (1, -1))):
        for step in range(segments + 1):
            angle = (corner + step / segments) * math.pi * 0.5
            points.append((sx * (w - r) + r * math.cos(angle), y, sz * (d - r) + r * math.sin(angle)))
    return points


def ellipse(half_width, half_depth, size, y, segments=40):
    return [(half_width * size * math.cos(i * math.tau / segments), y, half_depth * size * math.sin(i * math.tau / segments)) for i in range(segments)]


def lozenge(half_width, half_depth, taper, inset, y):
    """A bar with pointed ends. x is stretched several times over in game, so it insets less."""
    w, d = half_width - inset * 0.2, half_depth - inset
    t = taper * d / half_depth
    return [(w, y, 0.0), (w - t, y, d), (0.0, y, d), (-(w - t), y, d), (-w, y, 0.0), (-(w - t), y, -d), (0.0, y, -d), (w - t, y, -d)]


def drum_gem():
    """Snare and toms: a chunky rounded gem on a bright base."""
    mesh = Mesh('DrumGem')
    ring = lambda inset, y: rounded_rect(0.5, 0.20, 0.11, inset, y)
    mesh.band(ring(0.0, 0.0), ring(0.0, 0.06), (TRIM[0], 0.12), 1, 'out')
    mesh.band(ring(0.0, 0.06), ring(0.015, 0.075), (0.12, TRIM[1]), 1, 'out')
    mesh.band(ring(0.015, 0.075), ring(0.035, 0.075), SEAM, 2, 'up')
    mesh.band(ring(0.035, 0.075), ring(0.075, 0.26), BODY, 3, 'out')
    mesh.band(ring(0.075, 0.26), ring(0.095, 0.29), HOT, 4, 'out')
    mesh.band(ring(0.095, 0.29), ring(0.125, 0.29), (PANEL[0], 0.85), 5, 'up')
    mesh.cap(ring(0.125, 0.29), (0.0, 0.29, 0.0), (0.85, PANEL[1]), 5)
    mesh.write()


def cymbal_gem():
    """Cymbals: a thin bowed disc with a bell."""
    mesh = Mesh('CymbalGem')
    ring = lambda size, y: ellipse(0.5, 0.25, size, y)
    mesh.band(ring(1.0, 0.0), ring(1.0, 0.03), (TRIM[0], 0.12), 1, 'out')
    mesh.band(ring(1.0, 0.03), ring(0.97, 0.042), (0.12, TRIM[1]), 1, 'out')
    mesh.band(ring(0.97, 0.042), ring(0.93, 0.042), SEAM, 2, 'up')
    mesh.band(ring(0.93, 0.042), ring(0.42, 0.10), BODY, 3, 'up')
    mesh.band(ring(0.42, 0.10), ring(0.37, 0.108), HOT, 3, 'up')
    mesh.band(ring(0.37, 0.108), ring(0.20, 0.165), (PANEL[0], 0.86), 4, 'out')
    mesh.cap(ring(0.20, 0.165), (0.0, 0.18, 0.0), (0.86, PANEL[1]), 4)
    mesh.write()


def cymbal_ring():
    """The open hi-hat: the cymbal with its middle open."""
    mesh = Mesh('CymbalRing')
    ring = lambda size, y: ellipse(0.5, 0.25, size, y)
    mesh.band(ring(1.0, 0.0), ring(1.0, 0.03), (TRIM[0], 0.12), 1, 'out')
    mesh.band(ring(1.0, 0.03), ring(0.97, 0.042), (0.12, TRIM[1]), 1, 'out')
    mesh.band(ring(0.97, 0.042), ring(0.93, 0.042), SEAM, 2, 'up')
    mesh.band(ring(0.93, 0.042), ring(0.80, 0.09), BODY, 3, 'up')
    mesh.band(ring(0.80, 0.09), ring(0.72, 0.09), HOT, 3, 'up')
    mesh.band(ring(0.72, 0.09), ring(0.58, 0.03), (BODY[1], BODY[0]), 3, 'in')
    mesh.band(ring(0.58, 0.03), ring(0.56, 0.0), (SEAM[1], SEAM[0]), 5, 'in')
    mesh.write()


def kick_bar():
    """The kick: a low bar with pointed ends, lying on the highway under the other notes. Deeper
    front to back than they are, so it shows either side of a note that shares its beat."""
    mesh = Mesh('KickBar')
    ring = lambda inset, y: lozenge(0.5, 0.25, 0.10, inset, y)
    mesh.band(ring(0.0, 0.0), ring(0.0, 0.012), (TRIM[0], TRIM[1]), 0, 'out')
    mesh.band(ring(0.0, 0.012), ring(0.07, 0.05), BODY, 1, 'out')
    mesh.band(ring(0.07, 0.05), ring(0.10, 0.06), HOT, 2, 'up')
    # The top is the body ramp's dim end, so the bar reads as two bright edges, not a slab.
    mesh.band(ring(0.10, 0.06), ring(0.15, 0.06), (0.50, 0.40), 3, 'up')
    mesh.cap(ring(0.15, 0.06), (0.0, 0.06, 0.0), (0.40, 0.33), 3)
    mesh.write()


# ---------------------------------------------------------------- textures

def ramp(points, v):
    """Piecewise-linear lookup; points are (v, value), ascending."""
    if v <= points[0][0]:
        return points[0][1]
    for (v0, a), (v1, b) in zip(points, points[1:]):
        if v <= v1:
            return a + (b - a) * (v - v0) / (v1 - v0) if v1 > v0 else b
    return points[-1][1]


def to_srgb(linear):
    linear = min(max(linear, 0.0), 1.0)
    encoded = linear * 12.92 if linear <= 0.0031308 else 1.055 * linear ** (1.0 / 2.4) - 0.055
    return int(round(encoded * 255.0))


def write_png(path, width, height, pixel):
    """pixel(u, v) -> linear grey, v = 0 at the bottom row."""
    rows = bytearray()
    for row in range(height):
        rows.append(0)
        v = 1.0 - (row + 0.5) / height
        for column in range(width):
            value = to_srgb(pixel((column + 0.5) / width, v))
            rows += bytes((value, value, value))
    def chunk(kind, data):
        body = kind + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xffffffff)
    png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(bytes(rows), 9)) + chunk(b'IEND', b'')
    TEXTURES.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)
    # Square: the cooked mips of a 32 x 512 strip came out striped once its width reached one texel.
    # Uncompressed: block compression bands these gradients, and they are small.
    write_meta(path, {'FileType': 'png', 'Format': 'None', 'MIPs': True, 'Quality': 'h', 'Type': 'Default'})
    print(path.relative_to(ROOT))


def write_meta(path, settings):
    meta = Path(str(path) + '.meta')
    if not meta.exists():
        settings = dict(settings, GUID=secrets.token_hex(8))
        meta.write_text(json.dumps(settings, indent=4, sort_keys=True) + '\n')


def sheen(u):
    """A little brighter across the middle of the note, so it reads as rounded."""
    return 0.80 + 0.20 * math.cos((u - 0.5) * math.pi) ** 2


def gap(band_a, band_b):
    return (band_a[1] + band_b[0]) * 0.5


def textures():
    edges = [gap(TRIM, SEAM), gap(SEAM, BODY), gap(BODY, HOT), gap(HOT, PANEL)]

    def banded(values):
        """values: per band, (bottom, top). Hard steps at the gaps between bands."""
        bounds = [0.0] + edges + [1.0]
        points = []
        for (low, high), (a, b) in zip(zip(bounds, bounds[1:]), values):
            points += [(low + 1e-6, a), (high, b)]
        return points

    # Linear values, and the material multiplies the emissive ones several times over (its
    # EmissiveIntensity), so the trim and the crest go well past white and bloom while the body
    # keeps its colour. Diffuse: only the trim reflects.
    gem_diffuse = banded([(0.55, 1.0), (0.01, 0.01), (0.03, 0.03), (0.2, 0.2), (0.03, 0.03)])
    gem_emissive = banded([(0.40, 0.85), (0.0, 0.0), (0.055, 0.16), (0.36, 0.36), (0.17, 0.10)])
    write_png(TEXTURES / 'NoteGem_Diffuse.png', 256, 256, lambda u, v: ramp(gem_diffuse, v))
    write_png(TEXTURES / 'NoteGem_Emissive.png', 256, 256, lambda u, v: ramp(gem_emissive, v) * sheen(u))

    cymbal_diffuse = banded([(0.55, 1.0), (0.01, 0.01), (0.04, 0.04), (0.2, 0.2), (0.04, 0.04)])
    cymbal_emissive = banded([(0.40, 0.85), (0.0, 0.0), (0.16, 0.09), (0.36, 0.36), (0.14, 0.30)])
    def lathed(u, v):
        value = ramp(cymbal_emissive, v) * sheen(u)
        if BODY[0] <= v <= BODY[1]:
            # Lathe grooves across the bow.
            value *= 0.82 + 0.18 * math.cos((v - BODY[0]) / (BODY[1] - BODY[0]) * math.tau * 6.0)
        return value
    write_png(TEXTURES / 'NoteCymbal_Diffuse.png', 256, 256, lambda u, v: ramp(cymbal_diffuse, v))
    write_png(TEXTURES / 'NoteCymbal_Emissive.png', 256, 256, lathed)

    # Highway pieces and note markings are flat colours.
    write_png(TEXTURES / 'White.png', 4, 4, lambda u, v: 1.0)


if __name__ == '__main__':
    drum_gem()
    cymbal_gem()
    cymbal_ring()
    kick_bar()
    textures()
