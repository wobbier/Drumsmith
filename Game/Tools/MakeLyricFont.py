#!/usr/bin/env python3
"""Builds the venue's lyric font atlas (Docs/Venue-and-Band.md -> Lyrics).

Renders printable ASCII (32-126) of Inter, white on black, into
Assets/Textures/Venue/LyricFont.png, and writes each glyph's cell (UVs, top-left origin) and
advance into Game/Source/Venue/LyricFont.generated.h. Run from the repository root with Pillow:

    nix-shell -p 'python3.withPackages(p: [p.pillow])' --run 'python3 Game/Tools/MakeLyricFont.py'
"""
from PIL import Image, ImageDraw, ImageFont

FONT = "Engine/Assets/Fonts/Inter-Regular.ttf"
SIZE = 88            # pixels per em
STROKE = 2           # a little weight: Inter Regular reads thin from the back of the room
WIDTH = 1024
PAD = 4

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
cell_h = ascent + descent + 2 * PAD + 2 * STROKE
chars = [chr(c) for c in range(32, 127)]

# Pack cells left to right in rows; each cell is the glyph's advance wide.
cells = []
x = y = 0
for ch in chars:
    advance = font.getlength(ch) + STROKE
    w = int(advance + 0.999) + 2 * PAD
    if x + w > WIDTH:
        x, y = 0, y + cell_h
    cells.append((ch, x, y, w, advance))
    x += w
height = 1
while height < y + cell_h:
    height *= 2

image = Image.new("RGB", (WIDTH, height), (0, 0, 0))
draw = ImageDraw.Draw(image)
for ch, cx, cy, w, advance in cells:
    draw.text((cx + PAD + STROKE / 2, cy + PAD + STROKE), ch, font=font, fill=(255, 255, 255), stroke_width=STROKE // 2, stroke_fill=(255, 255, 255))
image.save("Assets/Textures/Venue/LyricFont.png")

with open("Game/Source/Venue/LyricFont.generated.h", "w") as out:
    out.write("#pragma once\n// Generated by Game/Tools/MakeLyricFont.py: don't edit.\n\n")
    out.write("namespace LyricFont\n{\n")
    out.write("    // A glyph's box in the atlas (UVs from the top left), one advance wide so neighbouring\n")
    out.write("    // glyph quads abut without overlapping, and that advance in line heights.\n")
    out.write("    struct Glyph { float U; float V; float Width; float Height; float Advance; };\n\n")
    out.write("    constexpr const char* kTexture = \"Assets/Textures/Venue/LyricFont.png\";\n")
    out.write("    constexpr char kFirst = ' ';\n")
    out.write(f"    constexpr int kCount = {len(cells)};\n")
    out.write("    constexpr Glyph kGlyphs[kCount] = {\n")
    for ch, cx, cy, w, advance in cells:
        out.write(f"        {{ {(cx + PAD) / WIDTH:.6f}f, {cy / height:.6f}f, {advance / WIDTH:.6f}f, {cell_h / height:.6f}f, {advance / cell_h:.6f}f }},   // {repr(ch)}\n")
    out.write("    };\n}\n")
print("atlas", WIDTH, "x", height, "cells", len(cells), "line height px", cell_h)
